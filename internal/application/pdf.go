// customFont implements entity.CustomFont for embedded Indic fonts.
type customFont struct {
	family string
	style  fontstyle.Type
	file   string
	bytes  []byte
}

func (c customFont) GetFamily() string        { return c.family }
func (c customFont) GetStyle() fontstyle.Type { return c.style }
func (c customFont) GetFile() string          { return c.file }
func (c customFont) GetBytes() []byte         { return c.bytes }

// PDFGenerator renders application PDFs.
type PDFGenerator struct {
	dir     string
	fontDir string
	family  string
	cfg     *entity.Config
}

// NewPDFGenerator creates a PDF generator, registering Indic fonts when present.
func NewPDFGenerator(dir, fontDir string) (*PDFGenerator, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	g := &PDFGenerator{dir: dir, fontDir: fontDir}

	fonts := loadFonts(fontDir)
	builder := config.NewBuilder()
	if len(fonts) > 0 {
		g.family = "noto"
		builder = builder.WithCustomFonts(fonts)
	}
	g.cfg = builder.Build()
	return g, nil
}

func loadFonts(fontDir string) []entity.CustomFont {
	if fontDir == "" {
		return nil
	}
	specs := []struct {
		file  string
		style fontstyle.Type
	}{
		{"NotoSansDevanagari-Regular.ttf", fontstyle.Normal},
		{"NotoSansDevanagari-Bold.ttf", fontstyle.Bold},
	}
	var out []entity.CustomFont
	for _, s := range specs {
		path := filepath.Join(fontDir, s.file)
		b, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		out = append(out, customFont{family: "noto", style: s.style, file: path, bytes: b})
	}
	return out
}

// Generate renders the PDF and returns its path.
func (g *PDFGenerator) Generate(userID, appID string, sch *domain.Scheme, formData map[string]any, lang string) (string, error) {
	m := maroto.New(g.cfg)

	titleStyle := props.Text{Size: 16, Style: fontstyle.Bold, Family: g.family, Top: 2}
	labelStyle := props.Text{Size: 10, Style: fontstyle.Bold, Family: g.family, Left: 1}
	valueStyle := props.Text{Size: 10, Family: g.family}

	m.AddRow(12, text.NewCol(12, sch.Name(lang), titleStyle))
	m.AddRow(8, text.NewCol(12, "Sahayak Application Form", props.Text{Size: 9, Family: g.family}))

	for _, f := range sch.ApplicationFields {
		value := formData[f.FieldName]
		m.AddRow(10,
			text.NewCol(5, f.Label(lang), labelStyle),
			text.NewCol(7, formatValue(value), valueStyle),
		)
	}

	m.AddRow(12, text.NewCol(12,
		"Generated by Sahayak | This is not an official submission.",
		props.Text{Size: 8, Family: g.family}))

	doc, err := m.Generate()
	if err != nil {
		return "", fmt.Errorf("render pdf: %w", err)
	}

	outDir := filepath.Join(g.dir, userID)
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(outDir, appID+".pdf")
	if err := os.WriteFile(path, doc.GetBytes(), 0o644); err != nil {
		return "", err
	}
	return path, nil
}

func formatValue(v any) string {
	if v == nil {
		return "-"
	}
	switch t := v.(type) {
	case string:
		if t == "" {
			return "-"
		}
		return t
	case bool:
		if t {
			return "Yes"
		}
		return "No"
	case float64:
		if t == float64(int64(t)) {
			return fmt.Sprintf("%d", int64(t))
		}
		return fmt.Sprintf("%g", t)
	case time.Time:
		return t.Format("02 Jan 2006")
	default:
		return fmt.Sprintf("%v", t)
	}
}

// CleanupOlderThan removes PDFs older than the given duration (retention policy).
func (g *PDFGenerator) CleanupOlderThan(maxAge time.Duration) {
	cutoff := time.Now().Add(-maxAge)
	_ = filepath.WalkDir(g.dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		if !strings.HasSuffix(strings.ToLower(path), ".pdf") {
			return nil
		}
		if info, err := d.Info(); err == nil && info.ModTime().Before(cutoff) {
			_ = os.Remove(path)
		}
		return nil
	})
}
