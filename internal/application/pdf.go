// customFont implements entity.CustomFont for embedded Indic fonts.
type customFont struct {
	family string
	style  fontstyle.Type
	file   string
	bytes  []byte
}

func (c customFont) GetFamily() string        { return c.family }
func (c customFont) GetStyle() fontstyle.Type { return c.style }
func (c customFont) GetFile() string          { return c.file }
func (c customFont) GetBytes() []byte         { return c.bytes }

// PDFGenerator renders application PDFs.
type PDFGenerator struct {
	dir        string
	fontDir    string
	family     string
	loaded     map[string]bool
	cfg        *entity.Config
	translator translate.Provider
}

// NewPDFGenerator creates a PDF generator, registering Indic fonts when present.
func NewPDFGenerator(dir, fontDir string, translator translate.Provider) (*PDFGenerator, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	g := &PDFGenerator{dir: dir, fontDir: fontDir, loaded: map[string]bool{}, translator: translator}

	fonts := loadFonts(fontDir, g.loaded)
	builder := config.NewBuilder()
	if len(fonts) > 0 {
		builder = builder.WithCustomFonts(fonts)
	}
	g.cfg = builder.Build()
	g.family = g.defaultFamily()
	return g, nil
}

// loadFonts registers every available Noto script font. Missing files are
// skipped, so the generator degrades gracefully when fonts are not installed.
func loadFonts(fontDir string, loaded map[string]bool) []entity.CustomFont {
	if fontDir == "" {
		return nil
	}
	var out []entity.CustomFont
	for _, spec := range scriptFonts {
		styles := []struct {
			suffix string
			style  fontstyle.Type
		}{
			{"Regular", fontstyle.Normal},
			{"Bold", fontstyle.Bold},
		}
		var found bool
		for _, s := range styles {
			file := spec.base + "-" + s.suffix + ".ttf"
			path := filepath.Join(fontDir, file)
			b, err := os.ReadFile(path)
			if err != nil {
				continue
			}
			found = true
			out = append(out, customFont{family: spec.family, style: s.style, file: path, bytes: b})
		}
		if found {
			loaded[spec.family] = true
		}
	}
	return out
}

// defaultFamily returns the family used for Latin/section text.
func (g *PDFGenerator) defaultFamily() string {
	if g.loaded["latin"] {
		return "latin"
	}
	if g.loaded["devanagari"] {
		return "devanagari"
	}
	return ""
}

// textRun is a single-script slice of a string paired with a font that
// contains all of its glyphs.
type textRun struct {
	text   string
	family string
}

// isASCIILetter reports runes absent from the Noto Indic fonts. gofpdf reads
// only cmap format 4, which in these files lacks A-Z a-z, so ASCII letters
// must always render with the default (Latin) font.
func isASCIILetter(r rune) bool {
	return (r >= 'A' && r <= 'Z') || (r >= 'a' && r <= 'z')
}

// splitRuns divides s into script runs: ASCII letters always take the default
// font, while Indic-script runs take their script font. Digits, spaces and
// common punctuation survive in every font, so they attach to the surrounding
// run — including a leading run, which keeps bullets ("-  ...") glued to the
// text that follows instead of stranding them in their own column.
func (g *PDFGenerator) splitRuns(s string) []textRun {
	var runs []textRun
	var cur strings.Builder
	kind := 0 // 0 = neutrals only so far, 1 = latin-letter run, 2 = indic run
	fam := ""
	flush := func() {
		if cur.Len() == 0 {
			return
		}
		f := g.family
		if kind == 2 {
			f = fam
		}
		runs = append(runs, textRun{text: cur.String(), family: f})
		cur.Reset()
		kind = 0
	}
	for _, r := range s {
		if isASCIILetter(r) {
			if kind == 2 {
				flush()
			}
			kind = 1
			cur.WriteRune(r)
			continue
		}
		if f := scriptFamily(string(r)); f != "" {
			ff := f
			if !g.loaded[f] {
				ff = g.family
			}
			if kind == 2 && fam == ff {
				cur.WriteRune(r)
				continue
			}
			if kind != 0 {
				flush()
			}
			kind = 2
			fam = ff
			cur.WriteRune(r)
			continue
		}
		cur.WriteRune(r)
	}
	flush()
	return runs
}

// apportion splits width into integer parts proportional to counts,
// each at least 1, summing exactly to width.
func apportion(width int, counts []int) []int {
	n := len(counts)
	out := make([]int, n)
	if n == 0 {
		return out
	}
	total := 0
	for _, c := range counts {
		total += c
	}
	if total == 0 {
		out[0] = width
		return out
	}
	used := 0
	for i, c := range counts {
		w := width * c / total
		if w < 1 {
			w = 1
		}
		out[i] = w
		used += w
	}
	// Fix rounding drift on the largest part.
	for used > width {
		big := 0
		for i := range out {
			if out[i] > out[big] {
				big = i
			}
		}
		if out[big] <= 1 {
			break
		}
		out[big]--
		used--
	}
	for used < width {
		big := 0
		for i := range counts {
			if counts[i] > counts[big] {
				big = i
			}
		}
		out[big]++
		used++
	}
	return out
}

// runCols renders s as one column per script run, sharing width
// proportionally. Single-run text keeps today's exact single-column layout.
func runCols(s string, width int, base func(fam string) props.Text, g *PDFGenerator) []core.Col {
	runs := g.splitRuns(s)
	if len(runs) == 0 {
		return []core.Col{text.NewCol(width, "", base(g.family))}
	}
	if len(runs) == 1 {
		return []core.Col{text.NewCol(width, runs[0].text, base(runs[0].family))}
	}
	counts := make([]int, len(runs))
	for i, r := range runs {
		counts[i] = len([]rune(r.text))
	}
	widths := apportion(width, counts)
	cols := make([]core.Col, len(runs))
	for i, r := range runs {
		cols[i] = text.NewCol(widths[i], r.text, base(r.family))
	}
	return cols
}

// scriptFamily maps the first non-Latin script found in s to a font family.
func scriptFamily(s string) string {
	for _, r := range s {
		switch {
		case r >= 0x0900 && r <= 0x097F:
			return "devanagari"
		case r >= 0x0980 && r <= 0x09FF:
			return "bengali"
		case r >= 0x0A00 && r <= 0x0A7F:
			return "gurmukhi"
		case r >= 0x0A80 && r <= 0x0AFF:
			return "gujarati"
		case r >= 0x0B00 && r <= 0x0B7F:
			return "oriya"
		case r >= 0x0B80 && r <= 0x0BFF:
			return "tamil"
		case r >= 0x0C00 && r <= 0x0C7F:
			return "telugu"
		case r >= 0x0C80 && r <= 0x0CFF:
			return "kannada"
		case r >= 0x0D00 && r <= 0x0D7F:
			return "malayalam"
		case r >= 0x0600 && r <= 0x06FF:
			return "arabic"
		}
	}
	return ""
}

// nativeWarning returns the disclaimer in the user's language when possible.
// It uses the configured translator, then falls back to bundled Hindi.
func (g *PDFGenerator) nativeWarning(ctx context.Context, lang string) string {
	if lang == "" || lang == "en" {
		return ""
	}
	if lang == "hi" {
		return warningHI
	}
	if g.translator != nil {
		if out, err := g.translator.Translate(ctx, warningEN, "en", lang); err == nil {
			out = strings.TrimSpace(out)
			if out != "" && !strings.EqualFold(out, warningEN) {
				return out
			}
		}
	}
	if g.loaded["devanagari"] {
		return warningHI
	}
	return ""
}

