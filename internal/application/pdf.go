// warningEN and warningHI are the bundled disclaimers shown in the yellow
// banner. warningEN is also the source string translated into the user's
// language at generation time.
const (
	warningEN = "IMPORTANT: This is NOT the official application form. It is a reference draft generated by Sahayak. Use it only as a guide to fill the official online application form. Do not submit this PDF as an official document."
	warningHI = "महत्वपूर्ण: यह आधिकारिक आवेदन पत्र नहीं है। यह सहायक द्वारा तैयार किया गया एक संदर्भ प्रारूप है। इसका उपयोग केवल आधिकारिक ऑनलाइन आवेदन पत्र भरने के संदर्भ के रूप में करें। इस पीडीएफ को आधिकारिक दस्तावेज़ के रूप में जमा न करें।"
)

