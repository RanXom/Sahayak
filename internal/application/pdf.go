// customFont implements entity.CustomFont for embedded Indic fonts.
type customFont struct {
	family string
	style  fontstyle.Type
	file   string
	bytes  []byte
}

func (c customFont) GetFamily() string        { return c.family }
func (c customFont) GetStyle() fontstyle.Type { return c.style }
func (c customFont) GetFile() string          { return c.file }
func (c customFont) GetBytes() []byte         { return c.bytes }

// PDFGenerator renders application PDFs.
type PDFGenerator struct {
	dir        string
	fontDir    string
	family     string
	loaded     map[string]bool
	cfg        *entity.Config
	translator translate.Provider
}

// NewPDFGenerator creates a PDF generator, registering Indic fonts when present.
func NewPDFGenerator(dir, fontDir string, translator translate.Provider) (*PDFGenerator, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	g := &PDFGenerator{dir: dir, fontDir: fontDir, loaded: map[string]bool{}, translator: translator}

	fonts := loadFonts(fontDir, g.loaded)
	builder := config.NewBuilder()
	if len(fonts) > 0 {
		builder = builder.WithCustomFonts(fonts)
	}
	g.cfg = builder.Build()
	g.family = g.defaultFamily()
	return g, nil
}

// loadFonts registers every available Noto script font. Missing files are
// skipped, so the generator degrades gracefully when fonts are not installed.
func loadFonts(fontDir string, loaded map[string]bool) []entity.CustomFont {
	if fontDir == "" {
		return nil
	}
	var out []entity.CustomFont
	for _, spec := range scriptFonts {
		styles := []struct {
			suffix string
			style  fontstyle.Type
		}{
			{"Regular", fontstyle.Normal},
			{"Bold", fontstyle.Bold},
		}
		var found bool
		for _, s := range styles {
			file := spec.base + "-" + s.suffix + ".ttf"
			path := filepath.Join(fontDir, file)
			b, err := os.ReadFile(path)
			if err != nil {
				continue
			}
			found = true
			out = append(out, customFont{family: spec.family, style: s.style, file: path, bytes: b})
		}
		if found {
			loaded[spec.family] = true
		}
	}
	return out
}

// defaultFamily returns the family used for Latin/section text.
func (g *PDFGenerator) defaultFamily() string {
	if g.loaded["latin"] {
		return "latin"
	}
	if g.loaded["devanagari"] {
		return "devanagari"
	}
	return ""
}

// familyFor returns the best available font family for a language, falling back
// to the default family when the script font is not installed.
func (g *PDFGenerator) familyFor(lang string) string {
	if f, ok := langFamily[lang]; ok && g.loaded[f] {
		return f
	}
	return g.family
}

// nativeWarning returns the disclaimer in the user's language when possible.
// It uses the configured translator, then falls back to bundled Hindi.
func (g *PDFGenerator) nativeWarning(ctx context.Context, lang string) string {
	if lang == "" || lang == "en" {
		return ""
	}
	if lang == "hi" {
		return warningHI
	}
	if g.translator != nil {
		if out, err := g.translator.Translate(ctx, warningEN, "en", lang); err == nil {
			out = strings.TrimSpace(out)
			if out != "" && !strings.EqualFold(out, warningEN) {
				return out
			}
		}
	}
	if g.loaded["devanagari"] {
		return warningHI
	}
	return ""
}

// Generate renders the PDF and returns its path.
func (g *PDFGenerator) Generate(ctx context.Context, userID, appID string, sch *domain.Scheme, formData map[string]any, lang string) (string, error) {
	m := maroto.New(g.cfg)
	family := g.familyFor(lang)

	titleStyle := props.Text{Size: 16, Style: fontstyle.Bold, Family: family, Top: 1}
	subStyle := props.Text{Size: 9, Family: family, Color: &props.Color{Red: 90, Green: 90, Blue: 90}}
	sectionStyle := props.Text{Size: 11, Style: fontstyle.Bold, Family: family, Top: 2, Bottom: 1}
	labelStyle := props.Text{Size: 10, Style: fontstyle.Bold, Family: family, Left: 1}
	valueStyle := props.Text{Size: 10, Family: family, Left: 1}
	bodyStyle := props.Text{Size: 9, Family: family, Left: 1, Right: 1}
	warnStyle := props.Text{Size: 9, Style: fontstyle.Bold, Family: family, Left: 2, Right: 2, Top: 2, Bottom: 2}

	// Header.
	m.AddAutoRow(text.NewCol(12, sch.Name(lang), titleStyle))
	m.AddAutoRow(text.NewCol(12, "Sahayak · Application Reference / आवेदन संदर्भ", subStyle))

	// Yellow disclaimer banner (English + native).
	m.AddAutoRow(text.NewCol(12, warningEN, warnStyle).WithStyle(yellowCell()))
	if native := g.nativeWarning(ctx, lang); native != "" {
		nativeFamily := g.familyFor(lang)
		m.AddAutoRow(text.NewCol(12, native, props.Text{
			Size: 9, Style: fontstyle.Bold, Family: nativeFamily, Left: 2, Right: 2, Top: 1, Bottom: 2,
		}).WithStyle(yellowCell()))
	}

	// Applicant details.
	m.AddAutoRow(text.NewCol(12, "Applicant Details", sectionStyle))
	for _, f := range sch.ApplicationFields {
		value := formatValue(formData[f.FieldName])
		m.AddAutoRow(
			text.NewCol(5, f.Label(lang), labelStyle).WithStyle(rowCell()),
			text.NewCol(7, value, valueStyle).WithStyle(rowCell()),
		)
	}

	// Required documents.
	if len(sch.RequiredDocuments) > 0 {
		m.AddAutoRow(text.NewCol(12, "Required Documents", sectionStyle))
		for _, d := range sch.RequiredDocuments {
			name := d.DocumentNameEN
			if lang == "hi" && d.DocumentNameHI != "" {
				name = d.DocumentNameHI
			}
			if d.IsMandatory {
				name += " *"
			}
			m.AddAutoRow(text.NewCol(12, "• "+name, bodyStyle))
		}
	}

	// Official application link.
	url := sch.ApplicationURL
	if url == "" {
		url = sch.OfficialURL
	}
	if url != "" {
		m.AddAutoRow(text.NewCol(12, "Official Application Link", sectionStyle))
		link := url
		m.AddAutoRow(text.NewCol(12, url, props.Text{Size: 9, Family: family, Left: 1, Hyperlink: &link}))
	}

	// Footer.
	m.AddAutoRow(text.NewCol(12,
		fmt.Sprintf("Generated by Sahayak on %s. This document is not an official submission.",
			time.Now().Format("02 Jan 2006")),
		props.Text{Size: 8, Family: family, Color: &props.Color{Red: 120, Green: 120, Blue: 120}, Top: 2, Align: align.Left}))

	doc, err := m.Generate()
	if err != nil {
		return "", fmt.Errorf("render pdf: %w", err)
	}

	outDir := filepath.Join(g.dir, userID)
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(outDir, appID+".pdf")
	if err := os.WriteFile(path, doc.GetBytes(), 0o644); err != nil {
		return "", err
	}
	return path, nil
}

func yellowCell() *props.Cell {
	return &props.Cell{BackgroundColor: &props.Color{Red: 255, Green: 235, Blue: 59}}
}

func rowCell() *props.Cell {
	return &props.Cell{
		BorderType:  border.Bottom,
		BorderColor: &props.Color{Red: 210, Green: 210, Blue: 210},
	}
}

func formatValue(v any) string {
	if v == nil {
		return "-"
	}
	switch t := v.(type) {
	case string:
		if strings.TrimSpace(t) == "" {
			return "-"
		}
		return t
	case bool:
		if t {
			return "Yes"
		}
		return "No"
	case float64:
		if t == float64(int64(t)) {
			return fmt.Sprintf("%d", int64(t))
		}
		return fmt.Sprintf("%g", t)
	case time.Time:
		return t.Format("02 Jan 2006")
	default:
		return fmt.Sprintf("%v", t)
	}
}

// CleanupOlderThan removes PDFs older than the given duration (retention policy).
func (g *PDFGenerator) CleanupOlderThan(maxAge time.Duration) {
	cutoff := time.Now().Add(-maxAge)
	_ = filepath.WalkDir(g.dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		if !strings.HasSuffix(strings.ToLower(path), ".pdf") {
			return nil
		}
		if info, err := d.Info(); err == nil && info.ModTime().Before(cutoff) {
			_ = os.Remove(path)
		}
		return nil
	})
}
