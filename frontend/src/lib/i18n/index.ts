const messages: Record<Lang, Dict> = { en, hi, ta };

function initialLang(): Lang {
	if (browser) {
		const saved = localStorage.getItem('sahayak_lang') as Lang | null;
		if (saved && messages[saved]) return saved;
		const nav = navigator.language.slice(0, 2);
		if (nav === 'en' || nav === 'hi' || nav === 'ta') return nav;
	}
	return 'hi';
}

export const language = writable<Lang>(initialLang());

language.subscribe((lang) => {
	if (browser) {
		localStorage.setItem('sahayak_lang', lang);
		document.documentElement.lang = lang;
	}
});

export function translate(lang: Lang, key: string): string {
	return messages[lang]?.[key] ?? messages.en[key] ?? key;
}
